// Workbook reference model (Phase 5, increment 2). Pure code: no DOM, no network, no storage.
//
// This is the browser-side twin of supabase/migrations/1102_workspace_sheets.sql. The database decides everything; this
// model applies the SAME rules to the SAME operations so that the browser can
//   * hold a local copy of a workbook and keep it current from pulled operations (applyRemote),
//   * predict how the server will answer (tests), and
//   * be checked against the real database: tests/fixtures/workspace-sheet-cases.json is run through this model by
//     tests/unit/workspace-spreadsheet.test.js and through PostgreSQL by supabase/tests/1102_workspace_sheet_parity_test.sql
//     (generated by tools/workspace-sheet-cases.mjs). The two must give the same answers.
//
// Where the database is loose, the model is loose in the same way, on purpose (see styleValid). Do not "fix" the model
// alone: change the database with a new migration, then change both.
//
// Shapes (all plain data, JSON friendly except the Maps inside a sheet):
//   workbook = { head_seq, sheets: [sheet], log: [entry], conflicts: [conflict], snapshots: [snapshot] }
//   sheet    = { id, name, position, serial, row_order, col_order, row_sizes, col_sizes, frozen_rows, frozen_cols,
//                deleted, styles: Map(style_id -> style), cells: Map("r:c" -> cell), filled }
//   cell     = { r, c, value, formula, style_id, last_seq }       r and c are row and column IDS, never positions
// A cell that was cleared, or that belonged to a deleted row or column, stays in `cells` as an empty marker (value,
// formula and style_id all null) with its last_seq. Markers are not counted and are never shown.

export const LIMITS = Object.freeze({
  sheets: 20,
  rows: 10000,
  cols: 100,
  filledCells: 50000,
  formulaLength: 1000,
  textLength: 32767,
  cellsPerOperation: 5000,
  idsPerOperation: 1000,
  operationsPerBatch: 200,
  stylesPerOperation: 200,
  stylesPerSheet: 500,
  sizeEntries: 500,
  firstRows: 100,
  firstCols: 26,
  firstFreeId: 1000,
  checkpointEvery: 200,
  operationBytes: 262144,
  sheetName: 31,
});

const INT_MAX = 2147483647;
const INT_MIN = -2147483648;

