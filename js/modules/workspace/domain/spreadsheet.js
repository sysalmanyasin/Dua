// ───────── errors ─────────
// The database answers an invalid operation with status "rejected" (SQLSTATE WS001). Inside the model that is a thrown
// Rejected, caught per operation.
class Rejected extends Error {}
const reject = (message) => {
  throw new Rejected(message);
};

// The whole call is refused before anything is written (bad envelope, too many operations, an integer out of range).
export class CallRefused extends Error {
  constructor(message) {
    super(message);
    this.name = 'CallRefused';
  }
}

// A pulled operation cannot be applied to this local copy: it has drifted from the server. Reload the workbook.
export class ReplicaOutOfSync extends Error {
  constructor(message) {
    super(message);
    this.name = 'ReplicaOutOfSync';
  }
}

// ───────── small validators (mirror the SQL helpers) ─────────
const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);

// workspace_json_int: a whole number, or null.
export function jsonInt(v) {
  return typeof v === 'number' && Number.isInteger(v) && Math.abs(v) < 1e18 ? v : null;
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
// workspace_uuid_or_null: the id in lower case, or null. Only text qualifies.
export const uuidOrNull = (v) => (typeof v === 'string' && UUID_RE.test(v) ? v.toLowerCase() : null);

// Characters the way PostgreSQL counts them (code points, not UTF-16 units).
export function charLength(s) {
  return s.length <= 1 ? s.length : [...s].length;
}
const trimSpaces = (s) => s.replace(/^ +| +$/g, ''); // PostgreSQL trim() removes spaces only

// The size jsonb::text would have (", " and ": " separators), in bytes. Used for the 500-byte style cap and the 256 KB operation cap.
function jsonbText(v) {
  if (v === null) return 'null';
  if (Array.isArray(v)) return `[${v.map(jsonbText).join(', ')}]`;
  if (typeof v === 'object')
    return `{${Object.keys(v)
      .map((k) => `${JSON.stringify(k)}: ${jsonbText(v[k])}`)
      .join(', ')}}`;
  return JSON.stringify(v);
}
const textBytes = (v) => new TextEncoder().encode(jsonbText(v)).length;

const HEX = /^#[0-9a-fA-F]{6}$/;
const between = (n, lo, hi) => n !== null && n >= lo && n <= hi;

// workspace_style_valid (migration 1111). If a key is present its value must be exactly valid; null is not valid. (1102 let a
// JSON null or a value of the wrong kind through for weight, size, alignments, border sides and several number format keys;
// 1111 closed that. Styles already stored under 1102 can still hold such values, so drawing still goes through sanitizeStyle.)
export function styleValid(p) {
  if (!isObj(p) || textBytes(p) > 500) return false;
  const keys = ['weight', 'size', 'color', 'bg', 'borders', 'halign', 'valign', 'numfmt'];
  if (Object.keys(p).some((k) => !keys.includes(k))) return false;
  const has = (o, k) => Object.prototype.hasOwnProperty.call(o, k);
  const oneOf = (v, set) => typeof v === 'string' && set.includes(v);
  if (has(p, 'weight') && !oneOf(p.weight, ['normal', 'bold'])) return false;
  if (has(p, 'size') && !(jsonInt(p.size) !== null && between(p.size, 8, 72))) return false;
  for (const k of ['color', 'bg']) {
    if (has(p, k) && (typeof p[k] !== 'string' || !HEX.test(p[k]))) return false;
  }
  if (has(p, 'halign') && !oneOf(p.halign, ['left', 'center', 'right'])) return false;
  if (has(p, 'valign') && !oneOf(p.valign, ['top', 'middle', 'bottom'])) return false;
  if (has(p, 'borders')) {
    if (!isObj(p.borders)) return false;
    for (const [side, v] of Object.entries(p.borders)) {
      if (!['top', 'right', 'bottom', 'left'].includes(side) || !oneOf(v, ['thin', 'medium', 'thick'])) return false;
    }
  }
  if (has(p, 'numfmt')) {
    const nf = p.numfmt;
    if (!isObj(nf)) return false;
    if (Object.keys(nf).some((k) => !['type', 'decimals', 'currency', 'pattern'].includes(k))) return false;
    if (has(nf, 'type') && !oneOf(nf.type, ['general', 'number', 'currency', 'percent', 'date'])) return false;
    if (has(nf, 'decimals') && !(jsonInt(nf.decimals) !== null && between(nf.decimals, 0, 10))) return false;
    if (has(nf, 'currency') && (typeof nf.currency !== 'string' || !/^[A-Z]{3}$/.test(nf.currency))) return false;
    if (has(nf, 'pattern') && !oneOf(nf.pattern, ['dd/mm/yyyy', 'yyyy-mm-dd', 'dd mmm yyyy'])) return false;
  }
  return true;
}

// The strict reading of a style, for drawing a cell and for building styles. Anything the database might let through
// that is not exactly right is dropped. Returns a new object with only well-formed parts.
export function sanitizeStyle(p) {
  const out = {};
  if (!isObj(p)) return out;
  if (p.weight === 'bold' || p.weight === 'normal') out.weight = p.weight;
  if (jsonInt(p.size) !== null && between(p.size, 8, 72)) out.size = p.size;
  for (const k of ['color', 'bg']) if (typeof p[k] === 'string' && HEX.test(p[k])) out[k] = p[k];
  if (['left', 'center', 'right'].includes(p.halign)) out.halign = p.halign;
  if (['top', 'middle', 'bottom'].includes(p.valign)) out.valign = p.valign;
  if (isObj(p.borders)) {
    const b = {};
    for (const side of ['top', 'right', 'bottom', 'left'])
      if (['thin', 'medium', 'thick'].includes(p.borders[side])) b[side] = p.borders[side];
    if (Object.keys(b).length) out.borders = b;
  }
  if (isObj(p.numfmt) && ['general', 'number', 'currency', 'percent', 'date'].includes(p.numfmt.type)) {
    const nf = { type: p.numfmt.type };
    if (jsonInt(p.numfmt.decimals) !== null && between(p.numfmt.decimals, 0, 10)) nf.decimals = p.numfmt.decimals;
    if (typeof p.numfmt.currency === 'string' && /^[A-Z]{3}$/.test(p.numfmt.currency)) nf.currency = p.numfmt.currency;
    if (['dd/mm/yyyy', 'yyyy-mm-dd', 'dd mmm yyyy'].includes(p.numfmt.pattern)) nf.pattern = p.numfmt.pattern;
    out.numfmt = nf;
  }
  return out;
}

// ───────── workbook and sheets ─────────
export function createWorkbook() {
  return {
    head_seq: 0,
    sheets: [],
    log: [],
    conflicts: [],
    snapshots: [],
    _opIndex: new Map(),
    _serial: 0,
    _conflictSerial: 0,
    _snapshotSerial: 0,
  };
}

const isFilled = (cell) => cell.value !== null || cell.formula !== null || cell.style_id !== null;
const keyOf = (r, c) => `${r}:${c}`;

function newSheet(wb, { id, name, position, row_order, col_order, row_sizes, col_sizes, frozen_rows, frozen_cols }) {
  wb._serial += 1;
  const sheet = {
    id,
    name,
    position,
    serial: wb._serial,
    row_order: row_order ? [...row_order] : Array.from({ length: LIMITS.firstRows }, (_, i) => i + 1),
    col_order: col_order ? [...col_order] : Array.from({ length: LIMITS.firstCols }, (_, i) => i + 1),
    row_sizes: { ...(row_sizes ?? {}) },
    col_sizes: { ...(col_sizes ?? {}) },
    frozen_rows: frozen_rows ?? 0,
    frozen_cols: frozen_cols ?? 0,
    structure_seq: 0, // seq of the last insert/delete of rows or columns (or restore); see guardsFormula
    deleted: false,
    styles: new Map(),
    cells: new Map(),
    filled: 0,
  };
  wb.sheets.push(sheet);
  return sheet;
}

export const liveSheets = (wb) => wb.sheets.filter((s) => !s.deleted).sort((a, b) => a.position - b.position || a.serial - b.serial);
export const findSheet = (wb, id) => wb.sheets.find((s) => s.id === id) ?? null;
export const findLiveSheet = (wb, id) => wb.sheets.find((s) => s.id === id && !s.deleted) ?? null;
const liveFilled = (wb) => wb.sheets.reduce((n, s) => (s.deleted ? n : n + s.filled), 0);

// ───────── applying a batch ─────────
// Mirrors workspace_apply_ops: the same envelope checks, the same numbering, the same answers. `ops` is a list of
// { operation_id, operation_type, payload [, base_seq] }. Mutates `wb`. Returns { results, head_seq }.
// Throws CallRefused for what the database refuses outright. (Who may write, and archived workbooks, are decided by the
// database; they are not modelled here.)
export function applyOps(wb, ops, opts = {}) {
  if (!Array.isArray(ops) || ops.length < 1 || ops.length > LIMITS.operationsPerBatch) throw new CallRefused('send 1 to 200 operations');
  for (const o of ops) {
    if (
      !isObj(o) ||
      uuidOrNull(o.operation_id) === null ||
      typeof o.operation_type !== 'string' ||
      !OPERATION_TYPES.includes(o.operation_type)
    ) {
      throw new CallRefused('every operation needs an operation_id and a known operation_type');
    }
  }
  // One thing can still refuse the whole call part-way through: a row or column id outside the integer range (the
  // database errors and undoes the batch). Only then do we pay for a copy to roll back to.
  const mayAbort = ops.some((o) => isObj(o.payload) && Array.isArray(o.payload.ids) && o.payload.ids.some(outOfIntRange));
  if (!mayAbort) return runBatch(wb, ops, opts);
  const copy = structuredClone(wb);
  const out = runBatch(copy, ops, opts);
  Object.assign(wb, copy);
  return out;
}

const outOfIntRange = (x) => jsonInt(x) !== null && (x > INT_MAX || x < INT_MIN);

function runBatch(wb, ops, { deviceId = null }) {
  const start = wb.head_seq;
  let head = start;
  const results = [];
  for (const o of ops) {
    const opId = uuidOrNull(o.operation_id);
    const type = o.operation_type;
    const payload = o.payload === undefined ? null : o.payload;
    const existing = wb._opIndex.get(opId);
    if (existing) {
      results.push({
        operation_id: opId,
        status: 'duplicate',
        seq: existing.seq,
        original_status: existing.result?.status ?? existing.status,
        result: existing.result,
      });
      continue;
    }
    head += 1;
    const tooBig = textBytes(payload) > LIMITS.operationBytes;
    let res;
    if (tooBig) {
      res = { status: 'rejected', reason: 'that operation is too large', effective: {} };
    } else {
      try {
        res = applyOne(wb, head, type, payload, false);
      } catch (e) {
        if (!(e instanceof Rejected)) throw e;
        res = { status: 'rejected', reason: e.message, effective: {} };
      }
    }
    const { effective, ...stored } = res;
    const status =
      res.status === 'rejected' ? 'rejected' : res.status === 'conflict' && (res.applied_cells ?? 0) === 0 ? 'conflict' : 'applied';
    const entry = {
      seq: head,
      op_id: opId,
      device_id: deviceId,
      op_type: type,
      base_seq: jsonInt(o.base_seq) ?? (isObj(payload) ? jsonInt(payload.base_seq) : null) ?? 0,
      payload: res.status === 'rejected' ? (tooBig ? {} : (payload ?? {})) : (effective ?? {}),
      status,
      result: stored,
    };
    wb.log.push(entry);
    wb._opIndex.set(opId, entry);
    results.push({ operation_id: opId, seq: head, ...stored });
  }
  if (head > start) {
    wb.head_seq = head;
    if (Math.floor(head / LIMITS.checkpointEvery) > Math.floor(start / LIMITS.checkpointEvery)) storeSnapshot(wb, head, 'checkpoint', null);
  }
  return { results, head_seq: head };
}

// What changed since seq N (workspace_pull): the operations that changed something, oldest first.
export function pull(wb, since = 0, limit = 200) {
  const n = Math.min(Math.max(limit ?? 200, 1), 500);
  return wb.log
    .filter((l) => l.status === 'applied' && l.seq > (since ?? 0))
    .slice(0, n)
    .map((l) => ({ seq: l.seq, op_id: l.op_id, op_type: l.op_type, author: null, payload: l.payload, applied_at: null }));
}

// Applies ONE operation. `trusted` is for operations that came back from the server (applyRemote): the server already
// decided, so no conflict is raised and no limit checked; a mismatch means this copy has drifted.
function applyOne(wb, seq, type, payload, trusted) {
  if (!isObj(payload)) reject('the operation needs a payload object');
  const sid = uuidOrNull(payload.sheet_id);

  if (type === 'add_sheet') {
    if (sid === null) reject('sheet_id must be a uuid');
    const name = typeof payload.name === 'string' ? trimSpaces(payload.name) : '';
    if (typeof payload.name !== 'string' || !between(charLength(name), 1, LIMITS.sheetName))
      reject('a sheet name must be 1 to 31 characters');
    if (findSheet(wb, sid)) reject('that sheet id is already used');
    const live = liveSheets(wb);
    const position =
      trusted && jsonInt(payload.position) !== null ? payload.position : live.length ? Math.max(...live.map((s) => s.position)) + 1 : 0;
    if (live.length >= LIMITS.sheets) reject('a workbook can have at most 20 sheets');
    if (live.some((s) => s.name.toLowerCase() === name.toLowerCase())) reject('a sheet with that name already exists');
    newSheet(wb, { id: sid, name, position });
    return { status: 'applied', effective: { sheet_id: sid, name, position } };
  }

  if (type === 'reorder_sheets') {
    if (!Array.isArray(payload.order)) reject('order must be a list of sheet ids');
    const names = payload.order.map(uuidOrNull);
    const live = liveSheets(wb);
    const want = live.map((s) => s.id).sort();
    if (names.length === 0 || names.includes(null) || JSON.stringify([...names].sort()) !== JSON.stringify(want)) {
      reject('order must list every sheet of the workbook exactly once');
    }
    names.forEach((id, i) => {
      findSheet(wb, id).position = i;
    });
    return { status: 'applied', effective: { order: names } };
  }

  // everything else addresses an existing sheet of this workbook
  const sh = sid === null ? null : findLiveSheet(wb, sid);
  if (!sh) reject('sheet not found');

  if (type === 'rename_sheet') {
    const name = typeof payload.name === 'string' ? trimSpaces(payload.name) : '';
    if (typeof payload.name !== 'string' || !between(charLength(name), 1, LIMITS.sheetName))
      reject('a sheet name must be 1 to 31 characters');
    if (liveSheets(wb).some((s) => s.id !== sid && s.name.toLowerCase() === name.toLowerCase()))
      reject('a sheet with that name already exists');
    sh.name = name;
    return { status: 'applied', effective: { sheet_id: sid, name } };
  }

  if (type === 'delete_sheet') {
    if (liveSheets(wb).length <= 1) reject('a workbook needs at least one sheet');
    sh.deleted = true;
    return { status: 'applied', effective: { sheet_id: sid } };
  }

  if (type === 'set_styles') return setStyles(sh, payload);
  if (type === 'set_cells') return setCells(wb, sh, sid, seq, payload, trusted);
  if (['insert_rows', 'delete_rows', 'insert_cols', 'delete_cols'].includes(type))
    return structure(wb, sh, sid, seq, type, payload, trusted);
  if (type === 'resize') return resize(sh, payload);
  reject(`the operation ${type} is not available yet`);
  return null;
}

function setStyles(sh, payload) {
  if (!Array.isArray(payload.styles) || !between(payload.styles.length, 1, LIMITS.stylesPerOperation))
    reject('styles must be a list of 1 to 200 styles');
  const next = new Map(sh.styles);
  for (const item of payload.styles) {
    const it = isObj(item) ? item : {};
    const id = jsonInt(it.style_id);
    if (id === null || !between(id, 1, 10000)) reject('a style id must be 1 to 10000');
    if (!styleValid(it.style)) reject('a style is not valid');
    next.set(id, structuredClone(it.style));
  }
  if (next.size > LIMITS.stylesPerSheet) reject('a sheet can have at most 500 styles');
  sh.styles = next;
  return { status: 'applied', effective: payload };
}

function setCells(wb, sh, sid, seq, payload, trusted) {
  const cells = payload.cells;
  if (!Array.isArray(cells) || !between(cells.length, 1, LIMITS.cellsPerOperation)) reject('cells must be a list of 1 to 5000 cells');
  const baseDefault = jsonInt(payload.base_seq);
  const rows = new Set(sh.row_order);
  const cols = new Set(sh.col_order);
  const pending = new Map(); // writes of this operation; nothing reaches the sheet unless every cell is valid
  const effective = [];
  const conflicts = [];
  const newConflicts = [];
  let applied = 0;

  for (const raw of cells) {
    const cell = isObj(raw) ? raw : {};
    const r = jsonInt(cell.r);
    const c = jsonInt(cell.c);
    if (r === null || c === null || r < 1 || c < 1 || r > INT_MAX || c > INT_MAX) reject('every cell needs a row id r and a column id c');
    const base = jsonInt(cell.base_seq) ?? baseDefault;
    if (!trusted && (base === null || base < 0)) reject('every cell needs a base_seq (the seq you last saw)');
    const nv = cell.value === undefined || cell.value === null ? null : cell.value;
    if (nv !== null && !['number', 'string', 'boolean'].includes(typeof nv)) reject('a cell value must be a number, text or true/false');
    if (typeof nv === 'string' && charLength(nv) > LIMITS.textLength) reject('a cell can hold at most 32,767 characters');
    let nf = null;
    if (cell.formula !== undefined && cell.formula !== null) {
      if (typeof cell.formula !== 'string') reject('a formula must be text');
      nf = cell.formula;
      if (nf.charAt(0) !== '=' || !between(charLength(nf), 2, LIMITS.formulaLength))
        reject('a formula starts with = and is at most 1,000 characters');
    }
    if (nv !== null && nf !== null) reject('a cell holds a value or a formula, not both');
    let ns = null;
    if (cell.style_id !== undefined && cell.style_id !== null) {
      ns = jsonInt(cell.style_id);
      if (ns === null || !sh.styles.has(ns)) reject('unknown style');
    }

    if (!(rows.has(r) && cols.has(c))) {
      if (trusted) throw new ReplicaOutOfSync('a pulled cell is outside the sheet');
      const summary = { conflict_id: null, r, c, kind: 'target_deleted' };
      newConflicts.push({
        summary,
        kind: 'target_deleted',
        target: { sheet_id: sid, r, c },
        server_state: null,
        local_state: { value: nv, formula: nf, style_id: ns },
      });
      conflicts.push(summary);
      continue;
    }
    // Structure guard (1112): a formula written from a copy older than the last change of rows or columns would point at the
    // wrong cells. A change made earlier in THIS batch does not count (head_seq only moves at the end of the batch).
    if (!trusted && nf !== null && staleForStructure(wb, sh, base)) {
      const summary = { conflict_id: null, r, c, kind: 'structure' };
      newConflicts.push({
        summary,
        kind: 'structure',
        target: { sheet_id: sid, r, c },
        server_state: { structure_seq: sh.structure_seq },
        local_state: { value: nv, formula: nf, style_id: ns },
      });
      conflicts.push(summary);
      continue;
    }
    const key = keyOf(r, c);
    const ex = pending.get(key) ?? sh.cells.get(key);
    if (!trusted && ex && ex.last_seq > base && (ex.value !== nv || ex.formula !== nf || ex.style_id !== ns)) {
      const summary = { conflict_id: null, r, c, kind: 'cell' };
      newConflicts.push({
        summary,
        kind: 'cell',
        target: { sheet_id: sid, r, c },
        server_state: { value: ex.value, formula: ex.formula, style_id: ex.style_id, last_seq: ex.last_seq },
        local_state: { value: nv, formula: nf, style_id: ns },
      });
      conflicts.push(summary);
      continue;
    }
    pending.set(key, { r, c, value: nv, formula: nf, style_id: ns, last_seq: seq });
    effective.push({ r, c, value: nv, formula: nf, style_id: ns });
    applied += 1;
  }

  let delta = 0;
  for (const [key, next] of pending) {
    const old = sh.cells.get(key);
    delta += (isFilled(next) ? 1 : 0) - (old && isFilled(old) ? 1 : 0);
  }
  if (!trusted && applied > 0 && liveFilled(wb) + delta > LIMITS.filledCells) reject('a workbook can hold at most 50,000 filled cells');

  for (const [key, next] of pending) sh.cells.set(key, next);
  sh.filled += delta;
  for (const n of newConflicts) {
    wb._conflictSerial += 1;
    n.summary.conflict_id = `conflict-${wb._conflictSerial}`;
    wb.conflicts.push({
      id: n.summary.conflict_id,
      kind: n.kind,
      target: n.target,
      server_state: n.server_state,
      local_state: n.local_state,
    });
  }
  return {
    status: conflicts.length > 0 ? 'conflict' : 'applied',
    applied_cells: applied,
    conflicts,
    effective: { sheet_id: sid, cells: effective },
  };
}

// True when `base` (the seq a copy last saw) is older than the sheet's last change of rows or columns that was made in an EARLIER
// batch. wb.head_seq is the committed head: a change made earlier in the batch being applied has structure_seq > head_seq.
const staleForStructure = (wb, sh, base) => base < sh.structure_seq && sh.structure_seq <= wb.head_seq;

function structure(wb, sh, sid, seq, type, payload, trusted) {
  const byCols = type === 'insert_cols' || type === 'delete_cols';
  const max = byCols ? LIMITS.cols : LIMITS.rows;
  const unit = byCols ? 'columns' : 'rows';
  const order = byCols ? sh.col_order : sh.row_order;
  const sb = jsonInt(payload.base_seq);
  if (!trusted && sb !== null && staleForStructure(wb, sh, sb)) {
    // the sender worked out its formula rewrite from positions that are no longer true
    wb._conflictSerial += 1;
    const id = `conflict-${wb._conflictSerial}`;
    wb.conflicts.push({
      id,
      kind: 'structure',
      target: { sheet_id: sid, op: type },
      server_state: { structure_seq: sh.structure_seq },
      local_state: { ids: payload.ids ?? null },
    });
    return { status: 'conflict', conflicts: [{ conflict_id: id, kind: 'structure' }], effective: payload };
  }
  if (!Array.isArray(payload.ids) || !between(payload.ids.length, 1, LIMITS.idsPerOperation)) reject('ids must be a list of 1 to 1000 ids');
  const ids = payload.ids.map(jsonInt);
  if (ids.some((x) => x !== null && (x > INT_MAX || x < INT_MIN))) throw new CallRefused('integer out of range'); // the database errors outright
  if (ids.includes(null) || new Set(ids).size !== ids.length || ids.some((x) => x < 1)) reject('ids must be distinct whole numbers');

  let nextOrder;
  if (type === 'insert_rows' || type === 'insert_cols') {
    if (ids.some((x) => x < LIMITS.firstFreeId)) reject('new ids start at 1000 (1 to 999 belong to the first grid)');
    const inOrder = new Set(order);
    if (ids.some((x) => inOrder.has(x))) reject('one of those ids is already in use');
    const wanted = new Set(ids);
    for (const cell of sh.cells.values()) {
      if (wanted.has(byCols ? cell.c : cell.r)) reject('one of those ids was used before and cannot be used again');
    }
    if (order.length + ids.length > max) reject(`that would be more than ${max} ${unit}`);
    let idx;
    if (payload.after === undefined || payload.after === null) {
      idx = 0;
    } else {
      const anchor = jsonInt(payload.after);
      idx = anchor === null ? -1 : order.indexOf(anchor) + 1;
      if (idx <= 0) {
        if (trusted) throw new ReplicaOutOfSync('a pulled insert names a row or column this copy does not have');
        wb._conflictSerial += 1;
        const id = `conflict-${wb._conflictSerial}`;
        wb.conflicts.push({
          id,
          kind: 'structure',
          target: { sheet_id: sid, op: type, after: payload.after },
          server_state: null,
          local_state: { ids },
        });
        return { status: 'conflict', conflicts: [{ conflict_id: id, kind: 'structure' }], effective: payload };
      }
    }
    nextOrder = [...order.slice(0, idx), ...ids, ...order.slice(idx)];
  } else {
    const gone = new Set(ids);
    nextOrder = order.filter((x) => !gone.has(x));
    if (nextOrder.length < 1) reject(`a sheet needs at least one ${byCols ? 'column' : 'row'} left`);
    // The cells are blanked, not removed: the empty row stays as a marker, so the id is never handed out again and a
    // stale edit to it is still recognised.
    for (const cell of sh.cells.values()) {
      if (gone.has(byCols ? cell.c : cell.r)) {
        if (isFilled(cell)) sh.filled -= 1;
        cell.value = null;
        cell.formula = null;
        cell.style_id = null;
        cell.last_seq = seq;
      }
    }
  }
  if (byCols) sh.col_order = nextOrder;
  else sh.row_order = nextOrder;
  sh.structure_seq = seq;
  return { status: 'applied', effective: payload };
}

function resize(sh, payload) {
  const next = { rows: sh.row_sizes, cols: sh.col_sizes };
  for (const k of ['rows', 'cols']) {
    const v = payload[k];
    if (v === undefined) continue;
    if (!isObj(v) || Object.keys(v).length > LIMITS.sizeEntries) reject('sizes must be an object of at most 500 entries');
    const order = new Set(k === 'rows' ? sh.row_order : sh.col_order);
    const sizes = { ...next[k] };
    for (const [key, val] of Object.entries(v)) {
      if (!/^[0-9]{1,10}$/.test(key)) reject('a size is keyed by a row or column id');
      if (val === null) delete sizes[key];
      else if (jsonInt(val) !== null && between(val, 10, 2000)) {
        if (order.has(Number(key))) sizes[key] = val;
      } else reject('a size is 10 to 2000 (or null to reset)');
    }
    next[k] = sizes;
  }
  sh.row_sizes = next.rows;
  sh.col_sizes = next.cols;
  return { status: 'applied', effective: payload };
}

// ───────── snapshots (restore points) ─────────
// workspace_build_snapshot
export function buildSnapshot(wb) {
  return {
    v: 1,
    sheets: liveSheets(wb).map((s) => ({
      id: s.id,
      name: s.name,
      position: s.position,
      row_order: [...s.row_order],
      col_order: [...s.col_order],
      row_sizes: { ...s.row_sizes },
      col_sizes: { ...s.col_sizes },
      frozen_rows: s.frozen_rows,
      frozen_cols: s.frozen_cols,
      styles: sortedStyles(s),
      cells: sortedCells(s).map((c) => [c.r, c.c, c.value, c.formula, c.style_id]),
    })),
  };
}

function storeSnapshot(wb, seq, kind, label) {
  const found = wb.snapshots.find((x) => x.seq === seq && x.kind === kind);
  if (found) return found;
  wb._snapshotSerial += 1;
  const snap = { id: `snapshot-${wb._snapshotSerial}`, seq, kind, label, snapshot: buildSnapshot(wb) };
  wb.snapshots.push(snap);
  return snap;
}

// workspace_snapshot_create: a manual restore point at the current seq (the existing one if this seq already has one).
export function createSnapshot(wb, label = null) {
  if (label !== null && label !== undefined && charLength(label) > 100) throw new CallRefused('a label is at most 100 characters');
  const clean = label === null || label === undefined ? null : trimSpaces(label) || null;
  const snap = storeSnapshot(wb, wb.head_seq, 'manual', clean);
  return { snapshot_id: snap.id, seq: wb.head_seq };
}

// workspace_sheet_restore (owner only in the database): puts the workbook back to a restore point as a NEW operation.
// Every restored cell gets the new seq, so an edit made offline against the old state becomes a conflict.
export function restoreSnapshot(wb, snapshotId) {
  const snap = wb.snapshots.find((x) => x.id === snapshotId);
  if (!snap) throw new CallRefused('no such restore point');
  storeSnapshot(wb, wb.head_seq, 'pre_restore', null);
  const seq = wb.head_seq + 1;
  const keep = new Set(snap.snapshot.sheets.map((s) => s.id));
  for (const s of wb.sheets) if (!keep.has(s.id)) s.deleted = true;
  for (const sh of snap.snapshot.sheets) {
    let sheet = findSheet(wb, sh.id);
    if (!sheet) sheet = newSheet(wb, sh);
    Object.assign(sheet, {
      name: sh.name,
      position: sh.position,
      row_order: [...sh.row_order],
      col_order: [...sh.col_order],
      row_sizes: { ...sh.row_sizes },
      col_sizes: { ...sh.col_sizes },
      frozen_rows: sh.frozen_rows,
      frozen_cols: sh.frozen_cols,
      structure_seq: seq, // a restore counts as a change of structure (1112)
      deleted: false,
      styles: new Map(sh.styles.map(([id, st]) => [id, structuredClone(st)])),
      cells: new Map(),
      filled: 0,
    });
    for (const [r, c, value, formula, styleId] of sh.cells) {
      sheet.cells.set(keyOf(r, c), { r, c, value: value ?? null, formula: formula ?? null, style_id: styleId ?? null, last_seq: seq });
      sheet.filled += 1;
    }
  }
  const entry = {
    seq,
    op_id: `restore-${seq}`,
    device_id: null,
    op_type: 'restore_snapshot',
    base_seq: wb.head_seq,
    payload: { snapshot_id: snap.id, snapshot_seq: snap.seq },
    status: 'applied',
    result: { status: 'applied' },
  };
  wb.log.push(entry);
  const restoredFrom = snap.seq;
  wb.head_seq = seq;
  return { status: 'restored', seq, restored_from_seq: restoredFrom };
}

// ───────── a local copy, kept current from the server ─────────
// Builds a workbook from workspace_workbook_open's answer. Fill it with addLoadedCells / addLoadedStyles, then pull from
// open.head_version to close the gap (workspace_pull) and feed each pulled operation to applyRemote.
export function loadWorkbook(open) {
  const wb = createWorkbook();
  wb.head_seq = open.head_version ?? 0;
  for (const s of open.sheets ?? []) newSheet(wb, s);
  return wb;
}

// Rows as returned by workspace_load_sheet: { row_id, col_id, value, formula, style_id, last_seq }.
export function addLoadedCells(wb, sheetId, rows) {
  const sh = findSheet(wb, sheetId);
  if (!sh) throw new ReplicaOutOfSync('unknown sheet');
  for (const x of rows) {
    const cell = {
      r: x.row_id,
      c: x.col_id,
      value: x.value ?? null,
      formula: x.formula ?? null,
      style_id: x.style_id ?? null,
      last_seq: x.last_seq,
    };
    const old = sh.cells.get(keyOf(cell.r, cell.c));
    sh.cells.set(keyOf(cell.r, cell.c), cell);
    sh.filled += (isFilled(cell) ? 1 : 0) - (old && isFilled(old) ? 1 : 0);
  }
}

// Rows of workspace_sheet_styles: { style_id, style }.
export function addLoadedStyles(wb, sheetId, rows) {
  const sh = findSheet(wb, sheetId);
  if (!sh) throw new ReplicaOutOfSync('unknown sheet');
  for (const x of rows) sh.styles.set(x.style_id, structuredClone(x.style));
}

// Applies one operation that came back from workspace_pull: { seq, op_type, payload }. The server has already decided;
// the payload holds only what was really written. Throws ReplicaOutOfSync when it does not fit this copy, and for a
// restore (restore_snapshot), which needs the workbook to be loaded again.
export function applyRemote(wb, entry) {
  if (entry.seq <= wb.head_seq) return; // already seen
  if (entry.op_type === 'restore_snapshot') throw new ReplicaOutOfSync('the workbook was restored: load it again');
  try {
    applyOne(wb, entry.seq, entry.op_type, entry.payload, true);
  } catch (e) {
    if (e instanceof Rejected) throw new ReplicaOutOfSync(`a pulled operation does not fit this copy (${e.message})`);
    throw e;
  }
  wb.head_seq = entry.seq;
}

// ───────── canonical state (what the parity test compares) ─────────
const sortedStyles = (s) => [...s.styles.entries()].sort((a, b) => a[0] - b[0]).map(([id, st]) => [id, structuredClone(st)]);
const sortedCells = (s) => [...s.cells.values()].filter(isFilled).sort((a, b) => a.r - b.r || a.c - b.c);

export function exportState(wb) {
  return {
    head_seq: wb.head_seq,
    sheets: liveSheets(wb).map((s) => ({
      id: s.id,
      name: s.name,
      position: s.position,
      row_order: [...s.row_order],
      col_order: [...s.col_order],
      row_sizes: { ...s.row_sizes },
      col_sizes: { ...s.col_sizes },
      frozen_rows: s.frozen_rows,
      frozen_cols: s.frozen_cols,
      styles: sortedStyles(s),
      cells: sortedCells(s).map((c) => [c.r, c.c, c.value, c.formula, c.style_id, c.last_seq]),
    })),
    pull: wb.log.filter((l) => l.status === 'applied').map((l) => ({ seq: l.seq, op_type: l.op_type, payload: l.payload })),
  };
}

