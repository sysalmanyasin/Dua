// Removes what the database generates randomly (conflict and snapshot ids), so answers can be compared.
export function stripIds(v) {
  if (Array.isArray(v)) return v.map(stripIds);
  if (isObj(v)) {
    const out = {};
    for (const [k, x] of Object.entries(v)) if (k !== 'conflict_id' && k !== 'snapshot_id') out[k] = stripIds(x);
    return out;
  }
  return v;
}

// ───────── reading helpers for screens ─────────
export function colLabel(index) {
  let n = index + 1;
  let s = '';
  while (n > 0) {
    const m = (n - 1) % 26;
    s = String.fromCharCode(65 + m) + s;
    n = Math.floor((n - 1) / 26);
  }
  return s;
}

export function parseColLabel(label) {
  if (!/^[A-Za-z]{1,3}$/.test(label)) return -1;
  let n = 0;
  for (const ch of label.toUpperCase()) n = n * 26 + (ch.charCodeAt(0) - 64);
  return n - 1;
}

// "C7" for the cell at row id / column id of this sheet (by their CURRENT position), or null if either is gone.
export function cellLabel(sheet, rowId, colId) {
  const ri = sheet.row_order.indexOf(rowId);
  const ci = sheet.col_order.indexOf(colId);
  return ri < 0 || ci < 0 ? null : `${colLabel(ci)}${ri + 1}`;
}

// The ids behind "C7", or null.
export function idsAtLabel(sheet, label) {
  const m = /^([A-Za-z]{1,3})([1-9][0-9]*)$/.exec(label);
  if (!m) return null;
  const c = sheet.col_order[parseColLabel(m[1])];
  const r = sheet.row_order[Number(m[2]) - 1];
  return c === undefined || r === undefined ? null : { r, c };
}

export const getCell = (sheet, rowId, colId) => {
  const cell = sheet.cells.get(keyOf(rowId, colId));
  return cell && isFilled(cell) ? cell : null;
};

// ───────── building operations ─────────
export const newOperationId = () => globalThis.crypto.randomUUID();

// Ids a sheet has seen: its current rows and columns plus every id any of its cells names (markers included).
export function usedIds(sheet, byCols) {
  const used = new Set(byCols ? sheet.col_order : sheet.row_order);
  for (const cell of sheet.cells.values()) used.add(byCols ? cell.c : cell.r);
  return used;
}

// New row or column ids: random 31-bit numbers, 1000 or more, not used here. (The database refuses an id it has seen.)
export function newIds(count, used, random = Math.random) {
  const out = [];
  const taken = new Set(used);
  while (out.length < count) {
    const id = LIMITS.firstFreeId + Math.floor(random() * (INT_MAX - LIMITS.firstFreeId));
    if (!taken.has(id)) {
      taken.add(id);
      out.push(id);
    }
  }
  return out;
}

export const buildOp = (operation_type, payload, operation_id = newOperationId()) => ({ operation_id, operation_type, payload });

// Turns what a person typed into a cell into { value, formula } or { error }.
export function parseCellInput(text) {
  const s = String(text ?? '');
  const t = s.trim();
  if (t === '') return { value: null, formula: null };
  if (t.startsWith('=') && t.length > 1) {
    return charLength(t) > LIMITS.formulaLength ? { error: 'A formula can be at most 1,000 characters.' } : { value: null, formula: t };
  }
  if (/^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/.test(t) && Number.isFinite(Number(t))) return { value: Number(t), formula: null };
  if (/^true$/i.test(t)) return { value: true, formula: null };
  if (/^false$/i.test(t)) return { value: false, formula: null };
  return charLength(s) > LIMITS.textLength ? { error: 'A cell can hold at most 32,767 characters.' } : { value: s, formula: null };
}
