// Works out which files the service worker must keep so the app opens with no connection, and writes them into sw.js.
//   node tools/sw-precache.mjs          rewrite the list in sw.js
//   node tools/sw-precache.mjs --check  exit 1 if sw.js is out of date (the unit test does the same)
// The list is everything index.html loads, plus every JS file reachable from the app entry, every module manifest, and the
// Emergency Billing screens, following literal `import ... from '...'` and `import('...')` paths and url() in CSS.
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const START = '/* PRECACHE:START (generated by tools/sw-precache.mjs; run it after adding files) */';
const END = '/* PRECACHE:END */';
const posix = (p) => p.split(sep).join('/');

function jsImports(file, text) {
  const out = [];
  for (const m of text.matchAll(/(?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)['"](\.{1,2}\/[^'"`$]+)['"]/g))
    out.push(resolve(dirname(file), m[1]));
  return out;
}
function cssUrls(file, text) {
  return [...text.matchAll(/url\(\s*['"]?(?!data:|https?:)([^'")\s]+)['"]?\s*\)/g)].map((m) => resolve(dirname(file), m[1].split('?')[0]));
}

export function computePrecache(root = ROOT) {
  const seen = new Set();
  const add = (abs) => {
    if (!existsSync(abs) || !statSync(abs).isFile() || seen.has(abs)) return;
    seen.add(abs);
    if (abs.endsWith('.js') || abs.endsWith('.mjs')) for (const d of jsImports(abs, readFileSync(abs, 'utf8'))) add(d);
    if (abs.endsWith('.css')) for (const d of cssUrls(abs, readFileSync(abs, 'utf8'))) add(d);
  };
  const html = readFileSync(join(root, 'index.html'), 'utf8');
  add(join(root, 'index.html'));
  for (const m of html.matchAll(/(?:href|src)="([^"#:]+\.[a-z0-9]+)"/g)) add(join(root, m[1]));
  add(join(root, 'js/core/app.js'));
  add(join(root, 'js/modules/index.js'));
  for (const d of readdirSync(join(root, 'js/modules'))) add(join(root, 'js/modules', d, 'manifest.js'));
  add(join(root, 'js/modules/ebill/ui/pos.js'));
  add(join(root, 'js/modules/ebill/ui/settings.js'));
  return [...seen].map((a) => posix(relative(root, a))).sort();
}

export const render = (list) => `${START}\n// prettier-ignore\nconst PRECACHE = ${JSON.stringify(list, null, 2)};\n${END}`;

export function currentList(swText) {
  const a = swText.indexOf(START);
  const b = swText.indexOf(END);
  if (a < 0 || b < 0) return null;
  return JSON.parse(swText.slice(swText.indexOf('=', a) + 1, swText.indexOf(';', swText.indexOf('=', a))).trim());
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const swPath = join(ROOT, 'sw.js');
  const text = readFileSync(swPath, 'utf8');
  const list = computePrecache();
  const next = text.slice(0, text.indexOf(START)) + render(list) + text.slice(text.indexOf(END) + END.length);
  if (process.argv.includes('--check')) {
    if (next !== text) {
      console.error('sw.js precache list is out of date. Run: node tools/sw-precache.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(swPath, next);
    console.log(`sw.js: ${list.length} files`);
  }
}
