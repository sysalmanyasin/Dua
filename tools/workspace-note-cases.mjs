// Builds supabase/tests/1101_workspace_note_cases_test.sql from tests/fixtures/workspace-note-cases.json, so the browser
// and the database validators are held to exactly the same cases. A unit test fails if the committed file is out of date.
// Run `node tools/workspace-note-cases.mjs` to regenerate it after changing the fixture.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const FIXTURE = join(root, 'tests/fixtures/workspace-note-cases.json');
export const OUTPUT = join(root, 'supabase/tests/1101_workspace_note_cases_test.sql');

const quote = (s) => `'${s.replace(/'/g, "''")}'`;

export function buildSql(cases) {
  const lines = [
    '-- GENERATED by tools/workspace-note-cases.mjs from tests/fixtures/workspace-note-cases.json. Do not edit by hand.',
    '-- The same cases are checked by the browser validator in tests/unit/workspace-validation.test.js.',
    '\\set ON_ERROR_STOP on',
    'begin;',
    'create function pg_temp.case_ok(got boolean, want boolean, msg text) returns void language plpgsql as $$',
    "begin if got is distinct from want then raise exception 'FAIL: % (database said %, expected %)', msg, got, want; end if; raise notice 'pass: %', msg; end $$;",
  ];
  for (const c of cases) {
    // Dollar-quoting with a tag the JSON can never contain keeps every character of the note exactly as written.
    lines.push(
      `select pg_temp.case_ok(public.workspace_note_valid($note$${JSON.stringify(c.note)}$note$::jsonb), ${c.valid}, ${quote(c.name)});`,
    );
  }
  lines.push('rollback;', '');
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, buildSql(JSON.parse(readFileSync(FIXTURE, 'utf8'))));
  console.log(`wrote ${OUTPUT}`);
}
