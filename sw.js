const WAIT_FOR_NETWORK_MS = 6000; // with a saved copy to fall back on, do not wait longer than this for a slow connection

async function precache(reload) {
  const cache = await caches.open(CACHE);
  await Promise.allSettled(
    PRECACHE.map(async (path) => {
      const res = await fetch(new Request(path, reload ? { cache: 'reload' } : {}));
      if (res.ok) await cache.put(path, res);
    }),
  );
  const shell = await cache.match('index.html');
  if (shell) await cache.put('./', shell.clone());
}

async function networkFirst(req) {
  const cache = await caches.open(CACHE);
  const saved = () => cache.match(req, { ignoreSearch: true });
  try {
    const hit = await saved();
    const net = fetch(req);
    const res = hit
      ? await Promise.race([net, new Promise((_, rej) => setTimeout(() => rej(new Error('slow')), WAIT_FOR_NETWORK_MS))])
      : await net;
    if (res.ok && res.type === 'basic') cache.put(req, res.clone());
    return res;
  } catch (err) {
    const hit = await saved();
    if (hit) return hit;
    if (req.mode === 'navigate') {
      const shell = (await cache.match('index.html')) || (await cache.match('./'));
      if (shell) return shell;
    }
    throw err;
  }
}

self.addEventListener('install', (e) => e.waitUntil(precache(false).then(() => self.skipWaiting())));
self.addEventListener('activate', (e) =>
  e.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('dua-shell-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  ),
);
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  if (new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(networkFirst(req));
});
// The page asks for a refresh now and then while online, so the saved copies do not drift from the live site.
self.addEventListener('message', (e) => {
  if (e.data?.type === 'REFRESH') e.waitUntil(precache(true));
});
